using System;

// 批选范围独立于列表筛选，所有入口仍必须通过可回收校验。
[Serializable]
public sealed class 天帝回收范围
{
    public int 品阶掩码=255;
    public int 类型; // 0全部、1属性、2分叉、3功能、4特性、5转化
    public int 位置=1; // 0整个背包、1当前筛选、2当前页
    public bool 匹配(道纹实例 纹)=>纹!=null&&!纹.是源纹&&!纹.是天赋&&
        (品阶掩码&(1<<(int)纹.品阶))!=0&&
        (类型==0||类型==1&&纹.分类==道纹分类.属性||类型==2&&纹.分类==道纹分类.分叉||类型==3&&纹.是功能道纹||类型==4&&纹.分类==道纹分类.特性||类型==5&&纹.分类==道纹分类.转化);
    public 天帝回收范围 副本()=>new 天帝回收范围{品阶掩码=品阶掩码,类型=类型,位置=位置};
}
