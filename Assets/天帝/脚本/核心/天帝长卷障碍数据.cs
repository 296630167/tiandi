using UnityEngine;

public enum 长卷障碍种类 { 古树, 松树, 岩石 }

// 图片采用1000×200左上原点坐标。脚底阻挡、场景显示与寻路读取同一份布点。
public sealed class 战斗场景障碍布点
{
    public 长卷障碍种类 种类 { get; }
    public Vector2 图片脚底 { get; }
    public Vector2 展示尺寸 { get; }
    public Vector2 阻挡半径 { get; }
    public 战斗场景障碍布点(长卷障碍种类 种类, float x, float y, float 宽, float 高, float 半宽, float 半高)
    {
        this.种类 = 种类; 图片脚底 = new Vector2(x, y); 展示尺寸 = new Vector2(宽, 高); 阻挡半径 = new Vector2(半宽, 半高);
    }
    public Vector2 世界脚底(天帝战斗地图 地图) => 地图.长卷位置(图片脚底.x, 图片脚底.y);
}

