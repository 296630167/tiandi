#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEngine;

public static class 天帝主角属性验证
{
    [Serializable] sealed class 报告
    {
        public List<string> 通过 = new List<string>();
        public List<string> 失败 = new List<string>();
        public List<string> 错误 = new List<string>();
    }
    // 既有单词条算式使用定向夹具；真实多词条随机生成由品阶专项验证。
    static 天帝道纹 单词条数据(int 种子, int 源纹编号 = 0)
    {
        var 数据 = 天帝道纹夹具.创建(种子, 源纹编号);
        foreach (var 纹 in 数据.道纹)
            if (纹.词条.Count > 1) 纹.词条.RemoveRange(1, 纹.词条.Count - 1);
        数据.重算(); return 数据;
    }
    public static string 运行()
    {
        var 结果 = new 报告();
        void 检查(string 名, bool 条件) => (条件 ? 结果.通过 : 结果.失败).Add(名);
        try
        {
            // 此组系数仅为验证夹具，不是游戏正式初值。
            var 配置 = new 主角属性配置 { 名字 = " 测试主角 ", 力量 = 2, 速度 = 3, 智力 = 4 };
            配置.血量.基础值 = 100; 配置.血量.力量系数 = 10;
            配置.灵力.基础值 = 50; 配置.灵力.智力系数 = 5;
            配置.防御.力量系数 = 1;
            配置.灵气护盾.智力系数 = 2;
            配置.移动速度.基础值 = 3; 配置.移动速度.速度系数 = 0.1f;
            配置.跑步速度.基础值 = 5; 配置.跑步速度.速度系数 = 0.2f;
            配置.攻击力.基础值 = 5; 配置.攻击力.力量系数 = 2; 配置.攻击力.速度系数 = 1; 配置.攻击力.智力系数 = 0.5f;
            using (var 主角 = new 天帝主角属性(配置))
            {
                检查("名字去首尾空白与基础属性", 主角.名字 == "测试主角" && 主角.力量 == 2 && 主角.速度 == 3 && 主角.智力 == 4 && 主角.等级 == 1);
                检查("七项衍生属性按独立系数计算", 主角.血量 == 120 && 主角.灵力 == 70 && 主角.防御 == 2 && 主角.灵气护盾 == 8 && Mathf.Approximately(主角.移动速度, 3.3f) && Mathf.Approximately(主角.跑步速度, 5.6f) && 主角.攻击力 == 14);
                检查("资源首次生成填满且上限别名一致", 主角.当前血量 == 主角.最大血量 && 主角.当前灵力 == 主角.最大灵力 && 主角.当前灵气护盾 == 主角.最大灵气护盾);
                配置.血量.基础值 = 999;
                主角.重算(); 检查("复制初始配置隔离外部修改", 主角.血量 == 120);
                配置.血量.基础值 = 100;
                检查("名字可改且拒绝空名", 主角.设置名字(" 无名 ") && 主角.名字 == "无名" && !主角.设置名字(" ") && !主角.设置名字(null));
                检查("当前资源独立且合法截断", 主角.设置当前资源(60, 30, 4) && 主角.当前血量 == 60 && 主角.血量 == 120 && 主角.当前灵力 == 30 && 主角.当前灵气护盾 == 4);
                检查("非法资源输入原子拒绝", !主角.设置当前资源(float.NaN, 1, 1) && !主角.设置当前资源(1, float.PositiveInfinity, 1) && !主角.设置当前资源(1, 1, float.NegativeInfinity) && 主角.当前血量 == 60 && 主角.当前灵力 == 30 && 主角.当前灵气护盾 == 4);
                主角.重算(); 主角.重算();
                检查("重复重算无累加或资源回复", 主角.攻击力 == 14 && 主角.当前血量 == 60 && 主角.当前灵力 == 30 && 主角.当前灵气护盾 == 4);
                配置.血量.基础值 = 0; 配置.血量.力量系数 = 5;
                检查("上限降低截断当前值", 主角.更新配置(配置) && 主角.血量 == 10 && 主角.当前血量 == 10);
                配置.血量.基础值 = 100;
                主角.更新配置(配置);
                检查("上限增大不自动回血", 主角.血量 == 110 && 主角.当前血量 == 10);
                检查("资源范围限制", 主角.设置当前资源(-1, 9999, 9999) && 主角.当前血量 == 0 && 主角.当前灵力 == 主角.灵力 && 主角.当前灵气护盾 == 主角.灵气护盾);
                检查("空配置更新不改变现状", !主角.更新配置(null) && 主角.血量 == 110);
            }
            配置.血量.基础值 = 100; 配置.血量.力量系数 = 10;
            for (int i = 0; i < 3; i++)
            {
                var 数据 = 单词条数据(7, i);
                using (var 主角 = new 天帝主角属性(配置, 数据))
                    检查("源纹" + (道纹属性)i + "只计一次且驱动对应属性", 主角.力量 == 2 + (i == 0 ? 10 : 0) && 主角.速度 == 3 + (i == 1 ? 10 : 0) && 主角.智力 == 4 + (i == 2 ? 10 : 0));
            }
            var 道纹 = 单词条数据(12); 道纹.设置玩家等级(6);
            for (int i = 1; i <= 5; i++) 道纹.解锁格子(new Vector2Int(i, 0));
            using (var 主角 = new 天帝主角属性(配置, 道纹))
            {
                var 力 = 道纹.道纹.Single(x => x.分类 == 道纹分类.属性 && x.属性 == 道纹属性.力量); 力.接口 = 9; 力.数值 = 3;
                var 血 = 道纹.道纹.Single(x => x.属性 == 道纹属性.血量); 血.接口 = 9; 血.数值 = 2;
                var 灵 = 道纹.道纹.Single(x => x.属性 == 道纹属性.灵力); 灵.接口 = 9; 灵.数值 = 3;
                var 功 = 道纹.道纹.Single(x => x.属性 == 道纹属性.连锁); 功.接口 = 9; 功.数值 = 999;
                var 元 = 道纹.道纹.Single(x => x.属性 == 道纹属性.雷); 元.接口 = 8; 元.数值 = 999;
                道纹.放置(力, new Vector2Int(1, 0));
                检查("有效力量自动驱动血量防御攻击力", 主角.力量 == 15 && 主角.血量 == 250 && 主角.防御 == 15 && 主角.攻击力 == 40);
                道纹.放置(血, new Vector2Int(2, 0)); 道纹.放置(灵, new Vector2Int(3, 0));
                检查("血量灵力道纹直接增加上限", 主角.血量 == 252 && 主角.灵力 == 73 && 主角.力量 == 15);
                道纹.放置(功, new Vector2Int(4, 0)); 道纹.放置(元, new Vector2Int(5, 0));
                检查("形态元素不污染主角基础属性", 功.生效 && 元.生效 && 主角.力量 == 15 && 主角.血量 == 252 && 主角.灵力 == 73 && 主角.攻击力 == 40);
                主角.设置当前资源(230, 72, 4);
                道纹.旋转(力);
                检查("上游旋转断链立即撤销所有属性加成", 主角.力量 == 12 && 主角.血量 == 220 && 主角.灵力 == 70 && 主角.当前血量 == 220 && 主角.当前灵力 == 70 && !元.生效);
                for (int i = 0; i < 5; i++) 道纹.旋转(力);
                检查("重接恢复上限而不回复当前资源", 主角.力量 == 15 && 主角.血量 == 252 && 主角.当前血量 == 220 && 主角.当前灵力 == 70);
                道纹.重算(); 道纹.重算();
                检查("道纹重复通知不重复加成", 主角.血量 == 252 && 主角.攻击力 == 40);
                道纹.收回(力);
                检查("卸载撤销加成保留源纹10点", 主角.力量 == 12 && 主角.血量 == 220 && 主角.灵力 == 70);
                道纹.设置玩家等级(10);
                检查("等级使用现有权威数据且不自动加属性", 主角.等级 == 10 && 道纹.技能点 == 4 && 主角.力量 == 12);
                主角.Dispose(); 主角.Dispose();
                道纹.放置(力, new Vector2Int(1, 0));
                检查("释放退订并拒绝后续写入", 主角.力量 == 12 && !主角.设置名字("新名") && !主角.更新配置(配置) && !主角.设置当前资源(1, 1, 1));
            }
            using (var 默认 = new 天帝主角属性())
                检查("默认名字和未配置初值为零", 默认.名字 == "我" && 默认.力量 == 0 && 默认.血量 == 0 && 默认.移动速度 == 0 && 默认.攻击力 == 0);
            var 非法配置 = new 主角属性配置 { 名字 = " ", 力量 = float.NaN, 速度 = float.PositiveInfinity, 智力 = -1, 血量 = null };
            非法配置.防御.基础值 = -4; 非法配置.攻击力.力量系数 = float.PositiveInfinity;
            using (var 非法 = new 天帝主角属性(非法配置))
                检查("负数非有限值与空配置项统一归零", 非法.名字 == "我" && 非法.力量 == 0 && 非法.速度 == 0 && 非法.智力 == 0 && 非法.血量 == 0 && 非法.防御 == 0 && 非法.攻击力 == 0);
            var 大配置 = new 主角属性配置 { 力量 = float.MaxValue }; 大配置.攻击力.力量系数 = float.MaxValue;
            using (var 极值 = new 天帝主角属性(大配置, 单词条数据(7)))
                检查("极大属性计算截断而不溢出", 极值.力量 == float.MaxValue && 极值.攻击力 == float.MaxValue);
        }
        catch (Exception 异常) { 结果.错误.Add(异常.ToString()); }
        string 目录 = Path.Combine(天帝构建工具.项目根, "生成/验证/主角属性-" + DateTime.UtcNow.ToString("yyyyMMdd-HHmmss"));
        Directory.CreateDirectory(目录);
        string 路径 = Path.Combine(目录, "hero-stats.json"); File.WriteAllText(路径, JsonUtility.ToJson(结果, true));
        if (结果.失败.Count > 0 || 结果.错误.Count > 0) throw new InvalidOperationException("主角属性验证失败：" + 路径);
        return 路径;
    }
}
#endif
