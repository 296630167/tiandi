using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using UnityEngine;

public static class 天帝伤害来源验证
{
    public static string 运行()
    {
        天帝数值同步检查.校验();
        var 结果 = new 天帝真实数值验证.报告(); var 字串 = new StringBuilder();
        void 检查(string 名, bool 对) => (对 ? 结果.通过 : 结果.失败).Add(名);
        bool 近(double 甲, double 乙) => Math.Abs(甲 - 乙) < Math.Max(.00001, Math.Abs(乙) * .000001);
        var 来源 = new 五行伤害分量(2, 3, 4, 5, 6);
        foreach (int 等级 in new[] { 1, 50, 100 }) foreach (double 形态 in new[] { 1, .8, .5, .35 })
        {
            var 包 = new 战斗伤害包(10, 20, 等级, 1.2, 形态, 1.1, 1.5, 来源);
            double 总 = (float)天帝数值.结算伤害(包, 等级 + 5, 20, .3);
            var 明 = 天帝数值.拆分伤害(包, 总, 20, .3); string 名 = 等级 + "/" + 形态;
            检查("分项之和等于原有最终伤害 " + 名, 近(明.合计, 总));
            检查("普通减防御元素减抗性 " + 名, 近(明.普通 / (总 - 明.普通), 10 * 天帝数值.防御留存(20, 等级) / 14));
            检查("五行按原通路比例分配 " + 名, 明.金 > 0 && 明.木 > 0 && 明.水 > 0 && 明.火 > 0 && 明.土 > 0 && 近(明.金 / 明.火, .4) && 近(明.木 / 明.土, .5));
        }
        for (int i = 0; i < 5; i++)
        {
            var 单 = new 五行伤害分量(i == 0 ? 10 : 0, i == 1 ? 10 : 0, i == 2 ? 10 : 0, i == 3 ? 10 : 0, i == 4 ? 10 : 0);
            var 包 = new 战斗伤害包(0, 10, 1, 1, 1, 1, 1, 单);
            var 明 = 天帝数值.拆分伤害(包, 天帝数值.结算伤害(包, 1, 20, .2), 20, .2);
            string 文 = 天帝伤害显示.文本(明, 字串); var 类 = (伤害来源)(i + 1);
            检查("纯元素只显示自身前缀与颜色 " + 类, 文.StartsWith("<color=#" + 天帝伤害显示.色值(类) + ">" + 类 + "-") && !文.Contains("普通-") && !文.Contains('\n'));
        }
        var 混 = new 战斗伤害包(10, 20, 1, 1, 1, 1, 1, 来源);
        var 混明 = 天帝数值.拆分伤害(混, 天帝数值.结算伤害(混, 1, 20, .2), 20, .2);
        string 混文 = 天帝伤害显示.文本(混明, 字串);
        检查("混合命中六个来源分行显示", 混文.Count(字 => 字 == '\n') == 5 && Enum.GetValues(typeof(伤害来源)).Cast<伤害来源>().Where(类 => 类 != 伤害来源.属性).All(类 => 混文.Contains(类 + "-")));
        检查("火红金金木绿互不混色", 天帝伤害显示.色值(伤害来源.火) == "FF6254" && 天帝伤害显示.色值(伤害来源.金) == "FFD15C" && 天帝伤害显示.色值(伤害来源.木) == "65D887");
        var 普 = new 战斗伤害包(10, 0, 1);
        var 普明 = 天帝数值.拆分伤害(普, 天帝数值.结算伤害(普, 1, 20, .2), 20, .2);
        检查("纯普通伤害保持原值并标普通", 近(普明.普通, 5) && 近(普明.合计, 5) && 天帝伤害显示.文本(普明, 字串).Contains("普通-5"));
        var 旧 = new 战斗伤害包(0, 10, 1);
        检查("旧聚合伤害不伪造具体元素", 天帝伤害显示.文本(天帝数值.拆分伤害(旧, 8, 20, .2), 字串).Contains("属性-8"));
        foreach (double 值 in new[] { .00000001, 1E12 })
        {
            var 包 = new 战斗伤害包(值, 值, 1, 1, 1, 1, 1, 来源);
            double 总 = (float)天帝数值.结算伤害(包, 1, 20, .2); var 明 = 天帝数值.拆分伤害(包, 总, 20, .2);
            检查("最低伤害和技术上限只作用于整包 " + 值, 近(明.合计, 总) && 近(明.金 / 明.火, .4));
        }
        检查("零伤害不生成来源文字", 天帝伤害显示.文本(default, 字串) == "");
        检查("微小分项不被显示成0", !天帝伤害显示.文本(new 战斗伤害明细(.0000002), 字串).Contains("普通-0</color>"));
        var 图 = new 天帝战斗地图(42, true); var 网 = new 天帝道纹(42, 天帝天赋.获取((int)天赋种类.普通人));
        for (int i = 0; i < 5; i++) 网.弹槽加成[0][(int)道纹属性.金 + i] = 来源.读取(i);
        using (var 人 = new 天帝主角属性(天帝普攻.主角配置(), 网))
        {
            var 攻 = 普攻参数.读取(网, 人);
            检查("普攻保留五行来源且仍共用原软上限", 近(攻.五行来源.总和, 20) && 近(攻.五行额外伤害, 天帝数值.五行伤害(网.弹槽加成[0], 1)));
            var 战 = new 天帝战斗系统(图, 网, 人, 战斗难度.普通, new 天帝通货(网, 42));
            var 列 = (List<战斗敌人>)战.敌人; 列.Clear();
            var 敌 = new 战斗敌人(new 战斗敌人布点(战斗敌人级别.王级, Vector2.right * 3), 战斗难度.普通);
            typeof(战斗敌人).GetProperty("已生成").SetValue(敌, true); 列.Add(敌);
            战斗伤害明细 反馈 = default; int 次数 = 0; bool 受伤方 = false;
            战.伤害分项反馈 += (点, 明细, 玩家) => { 反馈 = 明细; 受伤方 = 玩家; 次数++; };
            float 原血 = 敌.血量;
            战.推进(Vector2.zero, .25f);
            检查("真实投射命中只发一次分项反馈", 次数 == 1 && !受伤方 && 近(反馈.合计, 原血 - 敌.血量));
            检查("投射命中保留全部五行而非合并属性", 反馈.金 > 0 && 反馈.木 > 0 && 反馈.水 > 0 && 反馈.火 > 0 && 反馈.土 > 0 && 反馈.属性 == 0);
            原血 = 人.当前血量; float 原盾 = 人.当前灵气护盾;
            检查("主角同样接收分项伤害", 战.伤害玩家(new 战斗伤害包(2, 3, 1, 1, 1, 1, 1, new 五行伤害分量(0, 0, 0, 3, 0))) && 受伤方 && 反馈.普通 > 0 && 反馈.火 > 0 && 近(反馈.合计, 原血 + 原盾 - 人.当前血量 - 人.当前灵气护盾));
            int 原次数 = 次数;
            检查("无效伤害不触发分项或扣血", !战.伤害玩家(new 战斗伤害包(double.NaN, 0, 1)) && 次数 == 原次数);
        }
        string 目录 = Path.Combine(天帝构建工具.项目根, "生成/验证/伤害来源-" + DateTime.UtcNow.ToString("yyyyMMdd-HHmmss")); Directory.CreateDirectory(目录);
        File.WriteAllText(Path.Combine(目录, "report.json"), JsonUtility.ToJson(结果, true)); return 目录;
    }
}
#endif
