            var 死敌 = new 战斗敌人(new 战斗敌人布点(战斗敌人级别.头目, 地图.王位置), 战斗难度.普通);
            检查("未生成敌人不发奖励", !结算(待拾, 死敌));
            设置(死敌, "已生成", true);
            检查("活敌不发奖励", !结算(待拾, 死敌));
            设置(死敌, "血量", 0f);
            检查("余额溢出保留地面奖励待重试", 结算(待拾, 死敌) && !待拾.地面.Single().已拾取 && 满仓.灵石 == int.MaxValue - 2);
            满仓.抽取(宝盒种类.属性, out _, out _);
            检查("消费腾出余额后补领恰好一次", 待拾.自动拾取() == 1 && 待拾.拾取总量 == 75 && 待拾.自动拾取() == 0 && 满仓.灵石 == int.MaxValue - 2 - 天帝宝盒.价格(宝盒种类.属性) + 75);
            验证BOSS品阶(检查);
            统计掉落(检查, 目录);
        }
        catch (Exception 异常) { 结果.错误.Add(异常.ToString()); }
        File.WriteAllText(Path.Combine(目录, "report.json"), JsonUtility.ToJson(结果, true)); return 目录;
    }
    static void 验证BOSS品阶(Action<string, bool> 检查)
    {
        int[] 等级 = { 6, 49, 50, 69, 70, 84, 85, 99, 100, 105 };
        int[] 下限 = { 3, 3, 4, 4, 5, 5, 6, 6, 7, 7 };
        检查("BOSS最低档从稀有起步", 天帝道纹掉落.BOSS保底品阶(1) == 道纹品阶.稀有);
        foreach (var 难 in new[] { 战斗难度.普通, 战斗难度.困难 })
        foreach (var 赋 in new[] { 天赋种类.普通人, 天赋种类.天命之子 })
        {
            var 天赋 = 天帝天赋.获取((int)赋);
            道纹品阶 原抽(int 种子)
            {
                var 随机 = new System.Random(unchecked(种子 ^ 0x571A93)); 随机.NextDouble();
                return 天帝天赋效果.掉落品阶(天赋, () => 天帝道纹掉落.品阶结果(难, 随机.Next(10000)));
            }
            // 找到各个自然高阶的确定性种子，确保保底不会降级幸运或稀有随机结果。
            var 种子组 = new System.Collections.Generic.HashSet<int>(Enumerable.Range(0, 64));
            var 自然高阶 = new System.Collections.Generic.HashSet<道纹品阶>();
            for (int 种 = 0; 种 < 100000 && 自然高阶.Count < 4; 种++)
            {
                var 品 = 原抽(种);
                if (品 >= 道纹品阶.完美 && 自然高阶.Add(品)) 种子组.Add(种);
            }
            检查("自然完美至传说种子覆盖 " + 难 + "/" + 赋, 自然高阶.Count == 4);
            for (int 档 = 0; 档 < 等级.Length; 档++)
            {
                bool 必掉 = true, 品阶正确 = true, 词条正确 = true, 等级正确 = true, 去重 = true, 无套利 = true;
                foreach (int 种 in 种子组)
                {
                    var 图 = new 天帝战斗地图(种, true); var 网 = new 天帝道纹(种, 天赋);
                    var 落 = new 天帝道纹掉落(图, 网, 难); int 原数量 = 网.道纹.Count, 通知 = 0;
                    落.获得道纹 += _ => 通知++;
                    var 敌 = new 战斗敌人(new 战斗敌人布点(战斗敌人级别.王级, 图.王位置), 难, 等级[档] - 5);
                    设置(敌, "已生成", true); 设置(敌, "血量", 0f);
                    bool 出 = 结算(落, 敌);
                    必掉 &= 出 && 落.地面.Count == 1 && 落.拾取数 == 1 && 通知 == 1 && 网.道纹.Count == 原数量 + 1;
                    if (!出 || 落.地面.Count != 1) continue;
                    var 纹 = 落.地面.Single().道纹;
                    品阶正确 &= 纹.分类 == 道纹分类.属性 && (int)纹.品阶 == Math.Max(下限[档], (int)原抽(种))
                        && 天帝道纹掉落.BOSS保底品阶(敌.等级) == (道纹品阶)下限[档];
                    var 规 = 天帝道纹品阶.获取(纹.品阶); bool 五行 = 纹.词条.Any(词 => 天帝道纹属性.是五行(词.属性));
                    词条正确 &= 五行 ? 纹.词条.Count == 1 : 纹.词条.Count >= 规.最少词条 && 纹.词条.Count <= 规.最多词条;
                    等级正确 &= 敌.等级 == 等级[档] && 纹.物品等级 == Math.Min(等级[档], 100);
                    去重 &= !结算(落, 敌) && 落.自动拾取() == 0 && 落.地面.Count == 1 && 通知 == 1 && 网.道纹.Count == 原数量 + 1;
                    无套利 &= 天帝数值.道纹回收价(纹) < 天帝宝盒.价格(宝盒种类.属性);
                }
                string 名 = 难 + "/" + 赋 + "/BOSS Lv." + 等级[档];
                检查("必掉且仅入库一枚 " + 名, 必掉);
                检查("品阶达到下限且保留自然高阶 " + 名, 品阶正确);
                检查("按最终品阶生成词条并保留五行单词条 " + 名, 词条正确);
                检查("保底读实际等级而物品等级封顶100 " + 名, 等级正确);
                检查("BOSS死亡重复回调不发额外道纹 " + 名, 去重);
                检查("高阶BOSS道纹回收仍低于属性盒成本 " + 名, 无套利);
            }
        }
        var 地图 = new 天帝战斗地图(42, true); var 库存 = new 天帝道纹(42, 天帝天赋.获取((int)天赋种类.普通人));
        using (var 人 = new 天帝主角属性(天帝普攻.主角配置(), 库存))
        {
            var 战 = new 天帝战斗系统(地图, 库存, 人, 战斗难度.普通, 地图等级: 100);
            var 王 = 战.敌人.Single(敌 => 敌.布点.级别 == 战斗敌人级别.王级); 设置(王, "已生成", true);
            bool 杀 = 战.伤害敌人(王, 王.最大血量 * 10);
            检查("100级地图真实战斗击杀105级BOSS必掉传说", 杀 && 王.等级 == 105 && 战.掉落.地面.Count == 1
                && 战.掉落.地面.Single().道纹.品阶 == 道纹品阶.传说 && 战.掉落.地面.Single().已拾取);
        }
    }
    [Serializable] sealed class 掉落样本
    {
        public string 难度, 天赋;
        public int 局数 = 200, 总道纹, 总材料, 总灵石, 非BOSS分叉, 非BOSS低阶;
        public int[] 击杀 = new int[4], 道纹堆 = new int[4], 材料堆 = new int[4], 灵石堆 = new int[4], 空掉 = new int[4];
        public float 每局道纹, 每局材料, 每局灵石, 小怪空掉比例;
    }
    [Serializable] sealed class 掉落统计报告 { public System.Collections.Generic.List<掉落样本> 样本 = new System.Collections.Generic.List<掉落样本>(); }
    static void 统计掉落(Action<string, bool> 检查, string 目录)
    {
        var 报 = new 掉落统计报告();
        foreach (var 难 in new[] { 战斗难度.普通, 战斗难度.困难 })
        foreach (var 赋 in new[] { 天赋种类.普通人, 天赋种类.天命之子 })
        {
            var 项 = new 掉落样本 { 难度 = 难.ToString(), 天赋 = 赋.ToString() }; var 天赋 = 天帝天赋.获取((int)赋);
            bool 去重 = true, 随机独立 = true, 通知正确 = true;
            for (int 局 = 0; 局 < 项.局数; 局++)
            {
                int 种子 = 20261006 + 局; var 图 = new 天帝战斗地图(种子, true); var 网 = new 天帝道纹(种子, 天赋);
                var 钱 = new 天帝通货(网, 种子); var 盒 = new 天帝宝盒(网, 种子, 0);
                var 纹落 = new 天帝道纹掉落(图, 网, 难); var 货落 = new 天帝通货掉落(图, 网, 钱, 难); var 石落 = new 天帝灵石掉落(盒, 图.种子, 天赋);
                var 参考网 = new 天帝道纹(种子, 天赋);
                var 参考纹 = new 天帝道纹掉落(图, 参考网, 难); var 参考货 = new 天帝通货掉落(图, 参考网, new 天帝通货(参考网, 种子), 难);
                int 纹通知 = 0, 货通知 = 0, 石通知 = 0;
                纹落.获得道纹 += _ => 纹通知++; 货落.获得通货 += (_, n) => 货通知++; 石落.获得灵石 += _ => 石通知++;
                foreach (var 点 in 图.敌人)
                {
                    var 敌 = new 战斗敌人(点, 难); 设置(敌, "已生成", true); 设置(敌, "血量", 0f); int 类 = (int)点.级别;
                    bool 纹 = 结算(纹落, 敌), 货 = 结算(货落, 敌), 石 = 结算(石落, 敌);
                    if (纹 && 类 != (int)战斗敌人级别.王级)
                    {
                        var 物 = 纹落.地面.Last().道纹;
                        if (物.分类 == 道纹分类.分叉) 项.非BOSS分叉++;
                        else if (物.品阶 < 道纹品阶.稀有) 项.非BOSS低阶++;
                    }
                    项.击杀[类]++; if (纹) 项.道纹堆[类]++; if (货) 项.材料堆[类]++; if (石) 项.灵石堆[类]++; if (!纹 && !货 && !石) 项.空掉[类]++;
                    if (局 == 0)
                    {
                        for (int 次 = 0; 次 < 10; 次++) 去重 &= !结算(纹落, 敌) && !结算(货落, 敌) && !结算(石落, 敌);
                        随机独立 &= 结算(参考纹, 敌) == 纹 && 结算(参考货, 敌) == 货;
                    }
                }
                if (局 == 0)
                {
                    随机独立 &= 纹落.地面.Select(物 => JsonUtility.ToJson(物.道纹)).SequenceEqual(参考纹.地面.Select(物 => JsonUtility.ToJson(物.道纹)))
                        && 货落.地面.Select(物 => 物.种类 + ":" + 物.数量).SequenceEqual(参考货.地面.Select(物 => 物.种类 + ":" + 物.数量));
                }
                通知正确 &= 纹通知 == 纹落.拾取数 && 货通知 == 货落.拾取数 && 石通知 == 石落.地面.Count;
                项.总道纹 += 纹落.拾取数; 项.总材料 += 货落.拾取总量; 项.总灵石 += 石落.拾取总量;
            }
            string 前缀 = 难 + "/" + 赋;
            for (int 类 = 0; 类 < 4; 类++)
            {
                var 级 = (战斗敌人级别)类;
                double r = 天帝天赋效果.掉落概率(天赋, 天帝道纹掉落.基础概率(级, 难));
                double c = 天帝天赋效果.掉落概率(天赋, 天帝通货掉落.基础概率(级, 难));
                double s = 天帝天赋效果.掉落概率(天赋, 天帝灵石掉落.基础概率(级));
                bool 接近(int 数, double 概率) => Math.Abs((double)数 / 项.击杀[类] - 概率) <= Math.Max(.015, 6 * Math.Sqrt(概率 * (1 - 概率) / 项.击杀[类]));
                检查("三类掉率及空掉比例接近正式配置 " + 前缀 + "/" + 级, 接近(项.道纹堆[类], r) && 接近(项.材料堆[类], c) && 接近(项.灵石堆[类], s) && 接近(项.空掉[类], (1 - r) * (1 - c) * (1 - s)));
            }
            项.每局道纹 = (float)项.总道纹 / 项.局数; 项.每局材料 = (float)项.总材料 / 项.局数; 项.每局灵石 = (float)项.总灵石 / 项.局数;
            项.小怪空掉比例 = (float)项.空掉[0] / 项.击杀[0];
            检查("每局66敌人与BOSS稳定三类收益 " + 前缀, 项.击杀.SequenceEqual(new[] { 60 * 项.局数, 4 * 项.局数, 项.局数, 项.局数 }) && 项.道纹堆[3] == 项.局数 && 项.材料堆[3] == 项.局数 && 项.灵石堆[2] == 项.局数 && 项.灵石堆[3] == 项.局数);
            检查("掉落与未掉落均只能判定一次 " + 前缀, 去重);
            检查("非BOSS仍保留普通低阶与分叉掉落 " + 前缀, 项.非BOSS分叉 > 0 && 项.非BOSS低阶 > 0);
            检查("新增灵石随机流不干扰道纹和通货结果 " + 前缀, 随机独立);
            检查("通知只来自成功入库的实际掉落 " + 前缀, 通知正确);
            if (难 == 战斗难度.普通) 检查("多数小怪无物品掉落 " + 前缀, 项.小怪空掉比例 > .5f);
            报.样本.Add(项);
        }
        File.WriteAllText(Path.Combine(目录, "掉落统计.json"), JsonUtility.ToJson(报, true));
    }
