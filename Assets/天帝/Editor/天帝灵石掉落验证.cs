        => (bool)掉落.GetType().GetMethod("敌人死亡", BindingFlags.Instance | BindingFlags.NonPublic).Invoke(掉落, new object[] { 敌 });
    public static string 运行()
    {
        if (EditorApplication.isPlaying) throw new InvalidOperationException("灵石验证仅在编辑模式执行，不中断当前运行。");
        天帝数值同步检查.校验();
        var 结果 = new 天帝真实数值验证.报告();
        void 检查(string 名, bool 对) => (对 ? 结果.通过 : 结果.失败).Add(名);
        string 目录 = Path.Combine(天帝构建工具.项目根, "生成/验证/灵石掉落-" + DateTime.UtcNow.ToString("yyyyMMdd-HHmmss"));
        Directory.CreateDirectory(目录);
        try
        {
            var 地图 = new 天帝战斗地图(42, true);
            var 网 = new 天帝道纹(42, 天帝天赋.获取((int)天赋种类.普通人));
            var 宝盒 = new 天帝宝盒(网, 42, 天帝宝盒.开局灵石);
            using (var 人 = new 天帝主角属性(天帝普攻.主角配置(), 网))
            {
                var 战 = new 天帝战斗系统(地图, 网, 人, 战斗难度.普通, new 天帝通货(网, 42), 宝盒: 宝盒);
                int 提示次数 = 0, 提示数量 = 0, 余额次数 = 0;
                战.灵石掉落.获得灵石 += 数量 => { 提示次数++; 提示数量 += 数量; 战.灵石掉落.自动拾取(); };
                宝盒.余额改变 += () => 余额次数++;
                int[] 正式数量 = { 5, 25, 75, 200 };
                int 实际合计 = 0, 实际堆数 = 0;
                for (int i = 0; i < 4; i++)
                {
                    var 类 = (战斗敌人级别)i; var 敌 = 战.敌人.First(候选 => 候选.布点.级别 == 类);
                    设置(敌, "已生成", true); 设置(敌, "位置", 地图.王位置);
                    检查("正式灵石数量 " + 类, 天帝宝盒.击败奖励(类) == 正式数量[i]);
                    int 原余额 = 宝盒.灵石, 原堆 = 战.灵石掉落.地面.Count, 原经验 = 战.本局经验;
                    检查("真实击杀独立发经验 " + 类, 战.伤害敌人(敌, 敌.最大血量 * 10) && 战.本局经验 > 原经验);
                    bool 出 = 战.灵石掉落.地面.Count == 原堆 + 1; int 本次奖励 = 出 ? 正式数量[i] : 0;
                    实际合计 += 本次奖励; if (出) 实际堆数++;
                    检查("掉落数量或空掉余额正确 " + 类, 战.灵石掉落.地面.Count == 原堆 + (出 ? 1 : 0) && 宝盒.灵石 == 原余额 + 本次奖励);
                    if (出)
                    {
                        var 物 = 战.灵石掉落.地面.Last();
                        检查("远距离立即入库并保留吸附 " + 类, 物.数量 == 本次奖励 && 物.已拾取 && !物.演出结束 && 物.位置 == 地图.王位置);
                    }
                    检查("无论掉落或空掉死亡重入均不重抽 " + 类, !战.伤害敌人(敌, 1) && !结算(战.灵石掉落, 敌) && 战.灵石掉落.自动拾取() == 0 && 宝盒.灵石 == 原余额 + 本次奖励);
                }
                检查("只有实际掉落触发入库和通知且合计正确", 提示次数 == 实际堆数 && 余额次数 == 实际堆数 && 提示数量 == 实际合计 && 战.灵石掉落.拾取总量 == 实际合计 && 宝盒.灵石 == 天帝宝盒.开局灵石 + 实际合计);
                战.伤害玩家((float)天帝数值.取("damage.technical_hit_max"));
                for (int i = 0; i < 4; i++) 战.推进(Vector2.zero, .25f);
                检查("死亡后吸附仍结束且不丢余额", 人.当前血量 == 0 && 战.灵石掉落.地面.All(物 => 物.演出结束 && 物.显示位置 == Vector2.zero) && 宝盒.灵石 == 天帝宝盒.开局灵石 + 实际合计);
