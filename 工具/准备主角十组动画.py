def 投影(x, z, h, 角):
    # 纯2D姿态示意的正交投影，不创建3D资产或游戏模型。
    a = math.radians(角)
    sx = x * math.cos(a) + z * math.sin(a)
    深 = -x * math.sin(a) + z * math.cos(a)
    return (512 + sx, 928 - h * .82 + 深 * .574)


